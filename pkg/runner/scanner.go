package runner

import (
	"bufio"
	"compress/bzip2"
	"compress/gzip"
	"errors"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strings"
)

// Scanner reads lines from a file (plain, .gz, or .bz2) or stdin.
// It wraps bufio.Scanner to provide transparent decompression and file management.
type Scanner struct {
	file   *os.File       // The underlying file descriptor
	gzRead *gzip.Reader   // Explicit gzip reader (needs closing)
	scan   *bufio.Scanner // The actual scanner
	err    error          // Sticky error state
	buf    []byte         // Reusable buffer for the scanner
}

// NewScanner creates a scanner with a configurable maximum line size.
// Pass 0 to use the default bufio.Scanner size (64KB).
// Pass a larger number (e.g., 1024*1024) to handle longer lines.
func NewScanner(maxLineSize int) *Scanner {
	s := &Scanner{}
	if maxLineSize > 0 {
		s.buf = make([]byte, maxLineSize)
	}
	return s
}

// Start opens the file and initializes the scanner chain.
func (s *Scanner) Start(fn string) error {
	var r io.Reader

	// 1. Open Input Source
	if fn == "-" {
		s.file = os.Stdin
		r = os.Stdin
	} else {
		f, err := os.Open(fn)
		if err != nil {
			s.err = err
			return err
		}
		s.file = f
		r = f
	}

	// 2. Wrap with Decompressor if needed
	ext := strings.ToLower(filepath.Ext(fn))
	switch ext {
	case ".gz", ".bgz":
		gz, err := gzip.NewReader(r)
		if err != nil {
			s.err = err
			return ValidateErrors(err, s.Close())
		}
		s.gzRead = gz
		r = gz
	case ".bz2":
		// bzip2.NewReader returns an io.Reader, not a ReadCloser, so we don't need to close it specifically.
		// We usually wrap it in a bufio.Reader to reduce syscalls for the decompressor.
		r = bzip2.NewReader(bufio.NewReader(r))
	}

	// 3. Initialize bufio.Scanner
	s.scan = bufio.NewScanner(r)

	// Apply a custom buffer if requested
	if len(s.buf) > 0 {
		s.scan.Buffer(s.buf, len(s.buf))
	}

	return nil
}

// Scan advances the Scanner to the next token (line).
// It returns false when the scan stops, either by reaching the end of the input or an error.
func (s *Scanner) Scan() bool {
	if s.err != nil || s.scan == nil {
		return false
	}
	return s.scan.Scan()
}

// Text returns the most recent token generated by a call to Scan as a newly allocated string.
func (s *Scanner) Text() string {
	if s.scan == nil {
		return ""
	}
	return s.scan.Text()
}

// Bytes return the most recent token generated by a call to Scan.
// The underlying array may point to data that will be overwritten by a later call to Scan.
func (s *Scanner) Bytes() []byte {
	if s.scan == nil {
		return nil
	}
	return s.scan.Bytes()
}

// Err returns the first non-EOF error encountered by the Scanner.
func (s *Scanner) Err() error {
	if s.err != nil {
		return s.err
	}
	if s.scan != nil {
		return s.scan.Err()
	}
	return nil
}

// Close closes the file and any decompression readers.
// It is safe to call Close multiple times.
func (s *Scanner) Close() error {
	var errs []string

	// 1. Close Gzip Reader (flushes buffers)
	if s.gzRead != nil {
		if err := s.gzRead.Close(); err != nil {
			errs = append(errs, fmt.Sprintf("gzip close: %v", err))
		}
		s.gzRead = nil
	}

	// 2. Close File
	if s.file != nil && s.file != os.Stdin {
		if err := s.file.Close(); err != nil {
			errs = append(errs, fmt.Sprintf("file close: %v", err))
		}
		s.file = nil
	}

	if len(errs) > 0 {
		return errors.New(strings.Join(errs, "; "))
	}
	return nil
}
